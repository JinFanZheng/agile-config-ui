import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage()
page.on('framenavigated', (f) => f === page.mainFrame() && console.log('NAV →', f.url()))
page.on('response', (r) => r.status() >= 400 && console.log('HTTP', r.status(), r.url().slice(0, 110)))
await page.goto('http://localhost:5173/login')
await page.getByLabel('用户名').fill('admin')
await page.getByLabel('密码').fill('demo-stack-2026')
await page.getByRole('button', { name: '登录' }).click()
await page.waitForURL(/\/$/)
await page.goto('http://localhost:5173/settings')
await page.getByRole('radio', { name: '应用' }).check()
await page.waitForTimeout(300)
const dump = await page.evaluate(() => localStorage.getItem('agile-config-ui.settings'))
console.log('after check:', dump)
// 模拟登出+重登
await page.evaluate(() => localStorage.removeItem('agile-config-ui.session'))
await page.goto('http://localhost:5173/login')
await page.getByLabel('用户名').fill('admin')
await page.getByLabel('密码').fill('demo-stack-2026')
await page.getByRole('button', { name: '登录' }).click()
await page.waitForTimeout(1200)
console.log('landed:', page.url())
await browser.close()
